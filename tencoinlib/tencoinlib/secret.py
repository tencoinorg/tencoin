# tencoinlib/secret.py
"""
Tencoin secret generator and validator (TCS secrets).

This module is byte-for-byte compatible with the Tencoin Core node
(``tencoin/wallet/secret_engine.py``) and the node GUI. A secret generated
here is accepted by the node, and a secret generated by the node is accepted
here, with the same checksum and the same HASHLOCK hash.

A Tencoin secret is the text a hash-locked (C2 / C3) payment is locked with::

    TCS-XXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXCCCCC
    prefix(4) + 55 random characters (A-Z, 0-9) + 5 checksum characters
    = 64 characters in total (the prefix IS counted)

* The random part comes from the operating system's CSPRNG (``secrets``).
* checksum = first 5 characters (upper case) of the HEX digest of
  ``SHA-256("TCS-" + random_part)``. It is computed over prefix + random part,
  never over itself, and only exists to catch typos (a random typo slips
  through with probability 16^-5, about 1 in a million).
* The hash lock covers the WHOLE 64-character string, prefix and checksum
  included: ``secret_hash = SHA-256(text.strip().encode("utf-8"))``, a single
  round (see :func:`hash_preimage`). Nothing is ever case-folded, re-grouped
  or otherwise normalised: the text is the preimage.

Manual (free-form) secrets keep working. The checksum is only enforced for
text that *claims* to be a Tencoin secret, i.e. text starting with the exact
upper-case prefix ``TCS-``::

    starts with TCS-, 64 chars, A-Z / 0-9 after the prefix -> checksum verified
    starts with TCS- but length / characters are wrong      -> refused
                                                               (truncated / mistyped)
    starts with tcs- / Tcs- / ... (any other case)          -> soft warning only
    anything else                                           -> free-form manual secret

NEVER log a whole secret: log at most its first 8 characters, or its hash.
"""

import hashlib
import hmac
import secrets
from typing import List, NamedTuple

from .constants import (
    HASHLOCK_MIN_PREIMAGE,
    HASHLOCK_MAX_PREIMAGE,
    SECRET_PREFIX,
    SECRET_ALPHABET,
    SECRET_BODY_LENGTH,
    SECRET_CHECKSUM_LENGTH,
    SECRET_TOTAL_LENGTH,
)

__all__ = [
    "SecretError",
    "SecretFormatError",
    "ParsedSecret",
    "compute_checksum",
    "generate_secret",
    "claims_to_be_tencoin_secret",
    "check_secret",
    "is_valid_tencoin_secret",
    "soft_warnings",
    "parse_secret",
    "validate_secret",
    "secret_to_preimage",
    "hash_preimage",
    "MSG_CHECKSUM",
    "MSG_FORMAT",
    "MSG_CASE_WARNING",
]

MSG_CHECKSUM = "Invalid Tencoin Secret: checksum mismatch"
MSG_FORMAT = (
    "Invalid Tencoin Secret: expected 64 characters "
    "(TCS- + 55 characters A-Z/0-9 + 5-character checksum)"
)
MSG_CASE_WARNING = "Secrets are case-sensitive; Tencoin secrets are uppercase."


class SecretError(ValueError):
    """The text claims to be a Tencoin secret (starts with TCS-) but is malformed or has a bad checksum."""


# Same name as in the node (tencoin.wallet.secret_engine.SecretFormatError).
SecretFormatError = SecretError


class ParsedSecret(NamedTuple):
    """Result of :func:`parse_secret` (only produced for a well-formed secret)."""
    prefix: str            # always "TCS-"
    secret_body: str       # the 55 random characters
    checksum: str          # the 5 checksum characters, as given
    text: str              # the whole 64-character secret (stripped) - this is the preimage text
    checksum_valid: bool   # True if the checksum matches prefix + secret_body

    @property
    def preimage(self) -> bytes:
        """The HASHLOCK preimage: UTF-8 bytes of the whole secret text."""
        return self.text.encode("utf-8")


# ---------------------------------------------------------------------------
# checksum
# ---------------------------------------------------------------------------

def compute_checksum(body: str) -> str:
    """
    The 5 checksum characters of ``body`` = ``"TCS-" + random_part``
    (never including the checksum itself): upper-case hex of SHA-256, first 5 chars.
    """
    return hashlib.sha256(body.encode("ascii")).hexdigest().upper()[:SECRET_CHECKSUM_LENGTH]


# ---------------------------------------------------------------------------
# generation
# ---------------------------------------------------------------------------

def generate_secret() -> str:
    """A new random Tencoin secret: 64 characters, ready to be used as a HASHLOCK preimage text."""
    random_part = "".join(secrets.choice(SECRET_ALPHABET) for _ in range(SECRET_BODY_LENGTH))
    body = SECRET_PREFIX + random_part
    return body + compute_checksum(body)


# ---------------------------------------------------------------------------
# validation
# ---------------------------------------------------------------------------

def _as_text(text) -> str:
    """Stripped text, or "" for None / a non-string (never raises)."""
    return text.strip() if isinstance(text, str) else ""


def claims_to_be_tencoin_secret(text: str) -> bool:
    """True when the text (ends stripped) starts with the exact upper-case prefix ``TCS-``."""
    return _as_text(text).startswith(SECRET_PREFIX)


def check_secret(text: str) -> None:
    """
    Raise :class:`SecretError` if ``text`` claims to be a Tencoin secret but is malformed or has
    a wrong checksum. Free-form (non-``TCS-``) secrets pass untouched.
    """
    s = _as_text(text)
    if not s.startswith(SECRET_PREFIX):
        return
    tail = s[len(SECRET_PREFIX):]
    # length and characters are checked BEFORE the checksum is computed, so non-ASCII input
    # can never reach .encode("ascii") and never raises anything but SecretError.
    if len(s) != SECRET_TOTAL_LENGTH or any(c not in SECRET_ALPHABET for c in tail):
        raise SecretError(MSG_FORMAT)
    body, given = s[:-SECRET_CHECKSUM_LENGTH], s[-SECRET_CHECKSUM_LENGTH:]
    # strict, case-sensitive and constant-time: a lower-case checksum is NOT accepted, because
    # the whole text (checksum included) is the preimage and its case must not be "fixed" silently.
    if not hmac.compare_digest(compute_checksum(body), given):
        raise SecretError(MSG_CHECKSUM)


def is_valid_tencoin_secret(text: str) -> bool:
    """True for a well-formed Tencoin secret with a correct checksum (False for everything else, free-form included)."""
    if not claims_to_be_tencoin_secret(text):
        return False
    try:
        check_secret(text)
    except SecretError:
        return False
    return True


def soft_warnings(text: str) -> List[str]:
    """
    Warnings that must NOT block anything: text starting with ``tcs-`` in lower / mixed case is a
    legal manual secret, but it is most likely a generated secret whose case was changed.
    """
    s = _as_text(text)
    if s[:len(SECRET_PREFIX)].lower() == SECRET_PREFIX.lower() and not s.startswith(SECRET_PREFIX):
        return [MSG_CASE_WARNING]
    return []


def parse_secret(secret: str) -> ParsedSecret:
    """
    Split a Tencoin secret into prefix, random part and checksum.

    Raises:
        SecretError: if the text does not start with ``TCS-`` or is malformed
                     (wrong length / characters). A wrong CHECKSUM does not raise: it is
                     reported by ``checksum_valid`` so the caller can show a precise message
                     (use :func:`check_secret` if you want it to raise).
    """
    s = _as_text(secret)
    if not s.startswith(SECRET_PREFIX):
        raise SecretError(f"Not a Tencoin secret: it must start with {SECRET_PREFIX!r}")
    if len(s) != SECRET_TOTAL_LENGTH or any(c not in SECRET_ALPHABET for c in s[len(SECRET_PREFIX):]):
        raise SecretError(MSG_FORMAT)
    body, given = s[:-SECRET_CHECKSUM_LENGTH], s[-SECRET_CHECKSUM_LENGTH:]
    return ParsedSecret(
        prefix=SECRET_PREFIX,
        secret_body=body[len(SECRET_PREFIX):],
        checksum=given,
        text=s,
        checksum_valid=hmac.compare_digest(compute_checksum(body), given),
    )


def validate_secret(secret: str) -> bool:
    """
    True if ``secret`` is a well-formed Tencoin secret with a correct checksum.

    Never raises: malformed, too short, non-ASCII, non-string or free-form input returns False.
    """
    return is_valid_tencoin_secret(secret)


# ---------------------------------------------------------------------------
# preimage / hash (what goes on-chain)
# ---------------------------------------------------------------------------

def secret_to_preimage(text: str, *, verify_checksum: bool = True) -> bytes:
    """
    Secret text -> HASHLOCK preimage bytes: strip the ends, encode as UTF-8, 1..64 bytes.
    Identical to the node (wallet/hashlock.py ``secret_to_preimage``).

    If the text claims to be a Tencoin secret (starts with ``TCS-``) its checksum is verified
    first (disable with ``verify_checksum=False``). Free-form secrets are never checked.

    Raises:
        SecretError: malformed ``TCS-`` secret or wrong checksum, empty text, or a preimage
                     outside 1..64 bytes.
    """
    if verify_checksum:
        check_secret(text)
    raw = _as_text(text)
    if not raw:
        raise SecretError("Enter the secret.")
    encoded = raw.encode("utf-8")
    if len(encoded) < HASHLOCK_MIN_PREIMAGE:
        raise SecretError(f"The secret is too short: minimum {HASHLOCK_MIN_PREIMAGE} byte.")
    if len(encoded) > HASHLOCK_MAX_PREIMAGE:
        raise SecretError(
            f"The secret is too long: {len(encoded)} bytes after UTF-8 encoding, "
            f"maximum is {HASHLOCK_MAX_PREIMAGE}."
        )
    return encoded


def hash_preimage(secret: str, *, verify_checksum: bool = True) -> bytes:
    """
    ``SHA-256(preimage)``, single round: the ``secret_hash`` of a HASHLOCK (0xC2) output.

    The preimage is the WHOLE secret text (``TCS-`` prefix and checksum included), exactly as the
    node computes it. Typical use::

        builder.add_hashlock_output(..., preimage=secret_to_preimage(text))
    """
    return hashlib.sha256(secret_to_preimage(secret, verify_checksum=verify_checksum)).digest()
